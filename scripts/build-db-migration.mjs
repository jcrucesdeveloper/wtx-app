#!/usr/bin/env node
// Concatenates supabase/tables/*.sql (in file-name order) into the single
// migration the Supabase CLI applies with `supabase db push`.
//
// supabase/tables/ is the source of truth — edit those files, then run
// `pnpm db:migration` and commit both.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const tablesDir = join(root, 'supabase', 'tables')
const out = join(root, 'supabase', 'migrations', '20260925000000_accounts_sync_rooms.sql')

const files = readdirSync(tablesDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()

const header = [
  '-- GENERATED by scripts/build-db-migration.mjs — do not edit by hand.',
  '-- Source of truth: supabase/tables/*.sql (applied in file-name order).',
  '',
].join('\n')

const body = files
  .map((f) => `-- ===== ${f} =====\n\n${readFileSync(join(tablesDir, f), 'utf8').replace(/\r\n/g, '\n').trim()}\n`)
  .join('\n')

writeFileSync(out, `${header}\n${body}`)
console.log(`Wrote ${files.length} files → ${out}`)
