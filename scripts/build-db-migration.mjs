#!/usr/bin/env node
// Concatenates supabase/tables/*.sql (in file-name order) into
// supabase/schema.sql — one readable snapshot of the whole current schema.
//
// supabase/tables/ is the source of truth for what the schema looks like.
// Changes reach a database through supabase/migrations/ instead: migrations
// that are already applied never change, so a schema change means editing
// the table files AND adding a new migration with just that change. Then run
// `pnpm db:schema` and commit all three.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const tablesDir = join(root, 'supabase', 'tables')
const out = join(root, 'supabase', 'schema.sql')

const files = readdirSync(tablesDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()

const header = [
  '-- GENERATED by scripts/build-db-migration.mjs — do not edit by hand.',
  '-- Source of truth: supabase/tables/*.sql (applied in file-name order).',
  '-- Reference only: databases are built from supabase/migrations/.',
  '',
].join('\n')

const body = files
  .map((f) => `-- ===== ${f} =====\n\n${readFileSync(join(tablesDir, f), 'utf8').replace(/\r\n/g, '\n').trim()}\n`)
  .join('\n')

writeFileSync(out, `${header}\n${body}`)
console.log(`Wrote ${files.length} files → ${out}`)
